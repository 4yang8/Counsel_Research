    out = []
    for c, cl in p['shared']:
        out += [c, cl]
    out += [p['c5'], v[0], v[1][0], v[1][1], CHECK, v[2]]
    for c, cl in v[3:]:
        out += [c, cl]
    assert len(out) == 20, len(out)
    return '\n'.join(('상담사: ' if i % 2 == 0 else '내담자: ') + s for i, s in enumerate(out)) + '\n'


