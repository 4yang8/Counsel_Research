const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const trace=require('../static/paired_trace.js'),context={window:{},document:{}};
vm.runInNewContext(fs.readFileSync(require.resolve('../static/workflow.js'),'utf8'),context);
const build=context.window.Workflow.build;
const a=trace.create('counselor','tools',2,'P1','state_summary');
const payload={messages:[{role:'system',content:'system'},{role:'user',content:'BASE_NOTE'}],tools:[]};
trace.accept(a,{type:'request',iteration:1,payload});
trace.accept(a,{type:'tool_start',iteration:1,call_id:'a',name:'update_notes',arguments:'{}'});
let g=build(a.steps,1);assert.equal(g.nodes.filter(n=>n.kind==='tool').length,1);assert.equal(g.edges.filter(e=>e.kind==='feedback').length,0);
trace.accept(a,{type:'tool_result',call_id:'a',name:'update_notes',model_content:'SAVED_A'});
g=build(a.steps,2);assert.equal(g.edges.filter(e=>e.kind==='feedback').length,1);
trace.accept(a,{type:'request',iteration:2,payload});
trace.accept(a,{type:'tool_start',iteration:2,call_id:'b',name:'update_notes',arguments:'{}'});
trace.accept(a,{type:'tool_result',call_id:'b',name:'update_notes',model_content:'SAVED_B',is_error:true});
trace.accept(a,{type:'request',iteration:3,payload});
trace.accept(a,{type:'done',response:'ANSWER'});
g=build(a.steps,a.steps.length-1);
assert.equal(g.nodes.filter(n=>n.kind==='model').length,3);assert.equal(g.nodes.filter(n=>n.kind==='tool').length,2);
assert.equal(g.edges.filter(e=>e.kind==='call').length,2);assert.equal(g.edges.filter(e=>e.kind==='feedback').length,2);
assert.equal(new Set(g.nodes.map(n=>n.id)).size,g.nodes.length);
for(const e of g.edges)assert.ok(g.nodes.some(n=>n.id===e.from)&&g.nodes.some(n=>n.id===e.to));
const old=build(a.steps,1);assert.equal(old.nodes.length,2);assert.equal(old.edges.length,1);
const d=trace.create('client','delegate',1,'basic','state_summary');
trace.accept(d,{type:'request',iteration:1,payload});
trace.accept(d,{type:'tool_start',iteration:1,call_id:'delegate',name:'delegate_task',arguments:'{}'});
const meta={type:'agent_event',agent_id:'child',agent_name:'조회 담당',parent_agent_id:'main',parent_call_id:'delegate',depth:1};
trace.accept(d,{...meta,event:{type:'request',iteration:1,payload}});
trace.accept(d,{...meta,event:{type:'done',response:'CHILD_ANSWER'}});
trace.accept(d,{type:'tool_result',call_id:'delegate',name:'delegate_task',model_content:'CHILD_ANSWER'});
g=build(d.steps,d.steps.length-1);
assert.ok(g.edges.some(e=>e.kind==='delegate'));assert.ok(g.edges.some(e=>e.kind==='return'));assert.ok(g.edges.some(e=>e.kind==='feedback'));
console.log('PASS: distinct model/tool nodes, two tool rounds, stable call IDs, no future feedback, child delegation and return');
